/**
 * task-378 AC 4 (red-first; `bug-287`; `spec-020` §4.14 "What the commit carries", amended at the design gate; design
 * item 2) — the pure pieces of `src/memory/submit.ts` the `carries-content` check computes from committed blobs:
 *
 * - `describeCommittedSubmitContent(parent, commit)`: what `memory submit` declared, decided from the two stored blobs —
 *   equal, for a body edit, a field edit, a pure transition and a CRLF conversion (`core.autocrlf=false`), to the
 *   `Carries content:` line the REAL registered `memory.memorySubmit` wrote (`[]` where it wrote none); `null` when the
 *   commit blob has no `status` or its frontmatter does not parse;
 * - `isCarriesItem(item)`: the five forms of `spec-008` §2, and nothing else;
 * - `orderCarriesItems(items)`: fields by name, then the frontmatter text, the body, the file content, the line endings;
 *   duplicates dropped.
 *
 * The submits run in a throwaway repository (the `MEMORY_YAML` and `taskDoc` shape of
 * `test/core/memory-submit-content.test.ts`); the blobs are read back with `git cat-file blob`, byte for byte.
 *
 * Expected red: the three names are not exported from `src/memory/submit` (`tsc` TS2305; jest `TypeError: … is not a
 * function`); `parseCarriesContent` likewise from `src/memory/commit-message`.
 */
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { CORE_MODULES } from '../../src/core';
import type { CoreFn } from '../../src/core/registry';
import { parseCarriesContent } from '../../src/memory/commit-message';
import { describeCommittedSubmitContent, isCarriesItem, orderCarriesItems } from '../../src/memory/submit';
import { commitAll, makeTempGitRepo, removeTempDir, writeFixtureFile } from '../storage/helpers/git-fixture';

const MEMORY_YAML = `version: 1
types:
  task:
    path: "docs/memory/{release}/{id}.md"
    template:
      file: "memory/templates/task.md"
      frontmatter:
        required: [title, release]
    states:
      sequence: [draft, pending, backlog, in-progress, in-review, approved, done]
      gates:
        pending: { reject: draft }
        in-review: { reject: in-progress }
      waiting: [backlog, approved]
`;

const PATH = 'docs/memory/v0.2/task-101.md';

function taskDoc(fields: { state?: string; title?: string; extra?: string; body?: string } = {}): string {
  return `---
id: "task-101"          # auto-generated by wingfoil
type: task
title: "${fields.title ?? 'A task'}"   # REQUIRED
status: ${fields.state ?? 'draft'}          # auto-set by wingfoil
release: "v0.2"   # REQUIRED
${fields.extra ?? ''}tmpl_version: 260703
---

${fields.body ?? '## Description\n\nReal content.\n'}`;
}

function memorySubmitFn(): CoreFn<unknown, unknown> {
  const operation = CORE_MODULES.find((module) => module.name === 'memory')?.operations.memorySubmit;
  if (!operation) throw new Error('fixture bug: "memorySubmit" operation not registered on the memory module');
  return operation.fn as CoreFn<unknown, unknown>;
}

function git(repo: string, args: string[]): string {
  return execFileSync('git', ['-C', repo, ...args], { encoding: 'utf-8' });
}

/** The commit body exactly as git stores it: everything after the subject's blank line, or '' for a subject alone. */
function storedBody(repo: string): string {
  const raw = git(repo, ['cat-file', 'commit', 'HEAD']);
  const message = raw.slice(raw.indexOf('\n\n') + 2);
  const blank = message.indexOf('\n\n');
  return blank === -1 ? '' : message.slice(blank + 2);
}

describe('task-378 AC 4 — describeCommittedSubmitContent equals what memory submit wrote (spec-020 §4.14)', () => {
  let repo: string;

  beforeEach(() => {
    repo = makeTempGitRepo();
    git(repo, ['config', 'core.autocrlf', 'false']);
    writeFixtureFile(repo, '.wingfoil/memory.yaml', MEMORY_YAML);
    writeFixtureFile(repo, PATH, taskDoc());
    commitAll(repo, 'seed');
  });

  afterEach(() => removeTempDir(repo));

  /** Write `text` to the document, run the real submit, and return [parent blob, commit blob, declared items]. */
  async function submitted(text: string): Promise<{ parent: string; commit: string; declared: readonly string[] }> {
    writeFileSync(join(repo, PATH), text);
    const result = (await memorySubmitFn()({ root: repo, positional: 'task-101' })) as { ok: boolean };
    expect(result.ok).toBe(true);
    return {
      parent: git(repo, ['cat-file', 'blob', `HEAD^:${PATH}`]),
      commit: git(repo, ['cat-file', 'blob', `HEAD:${PATH}`]),
      declared: parseCarriesContent(storedBody(repo)) ?? [],
    };
  }

  it('a body edit: ["the body"], as the submit declared', async () => {
    const { parent, commit, declared } = await submitted(taskDoc({ body: '## Description\n\nFinished content.\n' }));
    expect(declared).toEqual(['the body']);
    expect(describeCommittedSubmitContent(parent, commit)).toEqual(declared);
  });

  it('a field edit and a body edit: the fields sorted by name, then the body, as the submit declared', async () => {
    const { parent, commit, declared } = await submitted(taskDoc({ title: 'A better task', extra: 'priority: "high"\n', body: 'New body.\n' }));
    expect(declared).toEqual(["frontmatter field 'priority'", "frontmatter field 'title'", 'the body']);
    expect(describeCommittedSubmitContent(parent, commit)).toEqual(declared);
  });

  it('a pure transition: nothing, and the submit wrote no line', async () => {
    const { parent, commit, declared } = await submitted(taskDoc());
    expect(declared).toEqual([]);
    expect(describeCommittedSubmitContent(parent, commit)).toEqual([]);
  });

  it('a CRLF conversion with core.autocrlf=false: ["the line endings"], as the submit declared', async () => {
    const { parent, commit, declared } = await submitted(taskDoc().replace(/\n/g, '\r\n'));
    expect(declared).toEqual(['the line endings']);
    expect(describeCommittedSubmitContent(parent, commit)).toEqual(declared);
  });

  it('a field edit plus a CRLF conversion: the field, then the line endings, as the submit declared', async () => {
    const { parent, commit, declared } = await submitted(taskDoc({ extra: 'priority: "high"\n' }).replace(/\n/g, '\r\n'));
    expect(declared).toEqual(["frontmatter field 'priority'", 'the line endings']);
    expect(describeCommittedSubmitContent(parent, commit)).toEqual(declared);
  });
});

describe('task-378 AC 4 — describeCommittedSubmitContent with no target state', () => {
  it('null when the commit blob has no status, or its frontmatter does not parse', () => {
    const parent = taskDoc();
    expect(describeCommittedSubmitContent(parent, parent.replace('status: draft          # auto-set by wingfoil\n', ''))).toBeNull();
    expect(describeCommittedSubmitContent(parent, '---\nid: [unclosed\nstatus: pending\n---\n\nBody.\n')).toBeNull();
  });
});

describe('task-378 AC 4 — isCarriesItem: the five forms of spec-008 §2', () => {
  it.each(["frontmatter field 'severity'", 'the frontmatter text (comments or formatting)', 'the body', 'the file content', 'the line endings'])('accepts %s', (item) => {
    expect(isCarriesItem(item)).toBe(true);
  });

  it.each(["frontmatter fields 'version'", 'the body.', 'The body', 'body', 'the line ending', ''])('refuses %j', (item) => {
    expect(isCarriesItem(item)).toBe(false);
  });
});

describe('task-378 AC 4 — orderCarriesItems: the declared order, duplicates dropped', () => {
  it('fields by name, then the frontmatter text, the body, the file content, the line endings', () => {
    expect(
      orderCarriesItems([
        'the line endings',
        'the body',
        "frontmatter field 'title'",
        'the file content',
        "frontmatter field 'priority'",
        'the body',
        'the frontmatter text (comments or formatting)',
        "frontmatter field 'title'",
      ]),
    ).toEqual(["frontmatter field 'priority'", "frontmatter field 'title'", 'the frontmatter text (comments or formatting)', 'the body', 'the file content', 'the line endings']);
  });

  it('an empty list stays empty', () => {
    expect(orderCarriesItems([])).toEqual([]);
  });
});
